import copy
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

import mido
import torch

from evaluate import evaluate_manifest, load_manifest, metrics
from hand_service import note_id, parse_source


class AllRightModel:
    def __call__(self, data):
        return torch.zeros((*data.shape[:2], 1))


class EvaluationTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.folder = Path(self.temp.name)
        source = mido.MidiFile(type=0)
        source.tracks.append(mido.MidiTrack([
            mido.Message('note_on', note=48), mido.Message('note_off', note=48, time=120),
            mido.Message('note_on', note=72, time=120), mido.Message('note_off', note=72, time=120)]))
        source.save(self.folder/'piece.mid')
        data = (self.folder/'piece.mid').read_bytes()
        _, pairs = parse_source(data)
        self.labels = dict(midi_sha256=hashlib.sha256(data).hexdigest(),
                           method='manual_hand_review', reviewer='synthetic test fixture',
                           notes=[dict(id=note_id(pair), hand=hand) for pair,hand in zip(pairs, ['LEFT','RIGHT'])])
        self.record = dict(id='synthetic-piece', work_id='synthetic-work', split='test',
                           midi='piece.mid', labels='labels.json',
                           license=dict(identifier='synthetic-test-data', source='generated by this test', reviewed=True))
        self.manifest = dict(version=1,pieces=[self.record])
        self.write()

    def write(self):
        (self.folder/'labels.json').write_text(json.dumps(self.labels))
        (self.folder/'manifest.json').write_text(json.dumps(self.manifest))
        return self.folder/'manifest.json'

    def test_metrics_match_an_analytical_confusion_matrix(self):
        result = metrics(['LEFT','RIGHT','LEFT','RIGHT'], ['LEFT','LEFT','RIGHT','RIGHT'])
        self.assertEqual(result['accuracy'], .5)
        self.assertEqual(result['confusion_matrix'], {'LEFT':{'LEFT':1,'RIGHT':1},'RIGHT':{'LEFT':1,'RIGHT':1}})
        for hand in ('LEFT','RIGHT'):
            self.assertEqual(result['per_hand'][hand], dict(precision=.5, recall=.5, f1=.5, support=2))
        self.assertIsNone(metrics([],[])['accuracy'])
        with self.assertRaises(ValueError):
            metrics(['LEFT'], [])

    def test_model_and_pitch_baseline_use_exact_same_reviewed_notes(self):
        result = evaluate_manifest(self.write(), AllRightModel())
        self.assertEqual(result['aggregate']['model']['accuracy'], .5)
        self.assertEqual(result['aggregate']['pitch_baseline']['accuracy'], 1.)
        self.assertEqual(result['piece_count'],1)
        self.assertEqual(result['aggregate']['model']['note_count'],2)
        self.assertEqual(result['pieces'][0]['reviewer'],'synthetic test fixture')
        self.assertTrue(result['limitations'])

    def test_unreviewed_rights_or_staff_only_labels_are_not_accepted(self):
        for field in ('rights','method','reviewer','checksum'):
            with self.subTest(field=field):
                record,labels=copy.deepcopy(self.record),copy.deepcopy(self.labels)
                if field == 'rights': self.record['license']['reviewed']=False
                elif field == 'method': self.labels['method']='musicxml_staff'
                elif field == 'reviewer': self.labels['reviewer']=''
                else: self.labels['midi_sha256']='wrong'
                with self.assertRaises(ValueError): load_manifest(self.write())
                self.record.clear();self.record.update(record);self.labels=labels

    def test_missing_or_duplicate_note_labels_are_rejected(self):
        original=copy.deepcopy(self.labels)
        for entries in (original['notes'][:1], original['notes']+original['notes'][:1]):
            self.labels['notes']=entries
            with self.assertRaises(ValueError): load_manifest(self.write())

    def test_duplicate_content_and_cross_split_works_are_rejected(self):
        extra=copy.deepcopy(self.record)
        extra['id']='different-id'
        self.manifest['pieces'].append(extra)
        with self.assertRaisesRegex(ValueError,'Duplicate MIDI'): load_manifest(self.write())
        extra['split']='train'
        with self.assertRaisesRegex(ValueError,'multiple splits'): load_manifest(self.write())

    def test_duplicate_json_keys_and_absent_test_split_are_errors(self):
        path=self.folder/'manifest.json'
        path.write_text('{"version":1,"version":2,"pieces":[]}')
        with self.assertRaisesRegex(ValueError,'Duplicate JSON'): load_manifest(path)
        self.record['split']='train'
        with self.assertRaisesRegex(ValueError,'No pieces'): evaluate_manifest(self.write(),AllRightModel())

    def test_local_authorization_does_not_claim_a_license_review(self):
        self.record['license']['reviewed']=False
        self.record['use_authorization']='user_authorized_local_evaluation'
        report=evaluate_manifest(self.write(),AllRightModel())
        self.assertFalse(report['pieces'][0]['license_declaration']['reviewed'])
        self.assertEqual(report['pieces'][0]['use_authorization'],'user_authorized_local_evaluation')

    def test_confirmed_track_mapping_must_match_every_note_label(self):
        self.labels['method']='user_confirmed_track_mapping'
        self.labels['track_hands']={'0':'LEFT'}
        with self.assertRaisesRegex(ValueError,'track mapping'): load_manifest(self.write())


if __name__ == '__main__':
    unittest.main()
